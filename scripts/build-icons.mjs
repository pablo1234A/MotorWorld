// Extracts a curated subset of Lucide icons (ISC license) into inline SVG strings
// for generated sites. Run: node scripts/build-icons.mjs
import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { join } from "node:path";

const NAMES = {
  spark: "sparkles", shield: "shield-check", bolt: "zap", leaf: "leaf", clock: "clock", chart: "chart-line",
  globe: "globe", heart: "heart", star: "star", truck: "truck", card: "credit-card", chat: "message-circle",
  layers: "layers", target: "target", key: "key-round", wrench: "wrench", map: "map-pin", cup: "coffee",
  book: "book-open", users: "users", check: "check", arrow: "arrow-right", arrowUpRight: "arrow-up-right",
  phone: "phone", mail: "mail", calendar: "calendar", car: "car", gauge: "gauge", fuel: "fuel",
  utensils: "utensils", wine: "wine", camera: "camera", palette: "palette", code: "code", cpu: "cpu",
  lock: "lock", rocket: "rocket", award: "award", graduation: "graduation-cap", play: "play",
  cart: "shopping-bag", plus: "plus", minus: "minus", x: "x", menu: "menu", at: "at-sign",
  link: "link", quote: "quote", sun: "sun", moon: "moon", trending: "trending-up",
  box: "package", refresh: "refresh-cw", search: "search", home: "house", building: "building",
  scale: "scale", stethoscope: "stethoscope", hammer: "hammer", flame: "flame", gem: "gem", compass: "compass",
};
const toAttrs = (o) => Object.entries(o).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${v}"`).join(" ");
const out = {};
for (const [alias, file] of Object.entries(NAMES)) {
  try {
    const mod = await import(pathToFileURL(join("node_modules/lucide-react/dist/esm/icons", file + ".mjs")).href);
    const node = mod.__iconData.node;
    out[alias] = node.map(([tag, attrs]) => `<${tag} ${toAttrs(attrs)}/>`).join("");
  } catch (e) {
    console.warn("missing icon", file);
  }
}
const body = `/* Generated by scripts/build-icons.mjs from lucide (ISC License, © Lucide Icons and Contributors). */\nexport const ICONS: Record<string, string> = ${JSON.stringify(out, null, 0)};\n\nexport const ICON_NAMES = Object.keys(ICONS);\n\nexport function icon(name: string | undefined, size = 22, cls = "wb-icon"): string {\n  const inner = (name && ICONS[name]) || ICONS.spark;\n  return \`<svg class="\${cls}" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${inner}</svg>\`;\n}\n`;
writeFileSync("src/render/icons.ts", body);
console.log("icons:", Object.keys(out).length);
